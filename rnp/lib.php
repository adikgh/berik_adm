	function rnp_rows_all($companies) {
		$rows = [];
		$one = count($companies) == 1;
		if (!$one) {
			// «Жалпы»: базадан/қолмен жолдар — барлық компанияның қосындысы, есептер — сол формуламен
			foreach (rnp_block('all', 'Жалпы', 'hd_d') as $r) {
				if ($r['t'] == 'auto' || $r['t'] == 'in') {
					$x = substr($r['k'], 4); $r['t'] = 'sum'; $r['of'] = [];
					foreach ($companies as $id => $n) $r['of'][] = "c{$id}_$x";
				}
				$rows[] = $r;
			}
		}
		foreach ($companies as $id => $n) foreach (rnp_block("c$id", $n, 'hd_g') as $r) {
			if ($r['t'] == 'title' && $one) $r['hide'] = true; // бір компания болса атауы жоғарыда тұр
			$rows[] = $r;
		}
		return $rows;
	}
