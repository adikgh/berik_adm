	// Көрінетін компаниялар: тек жоғарыда таңдалған компания
	function rnp_companies($company, $user_right) {
		$list = [];
		// жоғарыда компания таңдалса — тек сол; таңдалмаса Создатель (1) бәрін көреді
		$all = @$user_right['positions_id'] == 1 && !intval($company);
		$q = db::query("select id, name from company ".($all ? "" : "where id = '".intval($company)."'")." order by number asc, id asc");
		while ($q && $d = mysqli_fetch_assoc($q)) $list[intval($d['id'])] = $d['name'];
		return $list;
	}

